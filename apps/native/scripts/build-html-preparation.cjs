const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '../../..');

const result = esbuild.buildSync({ absWorkingDir: root,
  entryPoints: ['shared/file-preview/nativeHtmlPreparation.ts'], bundle: true, minify: true,
  format: 'iife', platform: 'browser', target: ['chrome100', 'safari16'], write: false,
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = '<!doctype html><html><head><meta charset="utf-8">'
  + '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'unsafe-inline\'">'
  + `</head><body><script>${script}</script></body></html>`;
const output = '// Generated by scripts/build-html-preparation.cjs. Edit shared/file-preview/nativeHtmlPreparation.ts.\n'
  + `export const htmlPreparationDocument = ${JSON.stringify(html)};\n`;
const target = path.join(root, 'apps/native/src/chat/html/htmlPreparation.generated.ts');
const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  if (previous !== output) throw new Error('Run node apps/native/scripts/build-html-preparation.cjs');
} else if (previous !== output) fs.writeFileSync(target, output);
